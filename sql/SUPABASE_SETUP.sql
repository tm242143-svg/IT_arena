-- Clean/recreate policies for repeatable setup.
drop policy if exists profiles_self_select on public.profiles;
drop policy if exists profiles_admin_select on public.profiles;
drop policy if exists profiles_self_insert on public.profiles;
drop policy if exists profiles_admin_update on public.profiles;
drop policy if exists questions_authenticated_select on public.questions;
drop policy if exists questions_admin_insert on public.questions;
drop policy if exists questions_admin_delete on public.questions;
drop policy if exists results_self_insert on public.quiz_results;
drop policy if exists results_self_select on public.quiz_results;
drop policy if exists results_admin_select on public.quiz_results;

create policy profiles_self_select on public.profiles for select to authenticated using (auth.uid()=id);
create policy profiles_admin_select on public.profiles for select to authenticated using (public.is_admin());
create policy profiles_self_insert on public.profiles for insert to authenticated with check (auth.uid()=id);
create policy profiles_admin_update on public.profiles for update to authenticated using (public.is_admin()) with check (public.is_admin());

create policy questions_authenticated_select on public.questions for select to authenticated using (true);
create policy questions_admin_insert on public.questions for insert to authenticated with check (public.is_admin());
create policy questions_admin_delete on public.questions for delete to authenticated using (public.is_admin());

create policy results_self_insert on public.quiz_results for insert to authenticated with check (auth.uid()=user_id);
create policy results_self_select on public.quiz_results for select to authenticated using (auth.uid()=user_id);
create policy results_admin_select on public.quiz_results for select to authenticated using (public.is_admin());

